"""The synthetic account universe: loading the packaged dataset.

The dataset is generated by ``data/generate_dataset.py`` (seeded,
deterministic) into ``data/accounts.json`` beside this module and
shipped with the package. Forty fictional specialty-insurance
accounts — submissions, claims extracts, endorsements, inspection
reports, correspondence, decision memos — including designed traps:
mid-term limit endorsements, a renamed insured, a dropped-and-
reinstated coverage, two near-identically named accounts, and one
correspondence carrying an instruction-injection attempt.

There is no real insurer, broker, account, or policy in it.
"""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path

from .ontology import Account

# The dataset's "present": documents run to May 2026, and the eval
# pack resolves briefs as of this date for determinism.
DATASET_PRESENT = date(2026, 6, 1)


def dataset_path() -> Path:
    return Path(__file__).resolve().parent / "data" / "accounts.json"


def load_accounts() -> dict[str, Account]:
    """All accounts in the packaged dataset, keyed by account_id."""
    raw = json.loads(dataset_path().read_text(encoding="utf-8"))
    accounts = {}
    for item in raw:
        account = Account.model_validate(item)
        accounts[account.account_id] = account
    return accounts
